
package tugasp2praktikum;

public class operasiMatematika {
    
    public static void main(String[] args) {
        double angkaPertama = 22.0;
        double angkaKedua = 33.0;

        double tambah = angkaPertama + angkaKedua;
        double kurang = angkaPertama - angkaKedua;
        double kali = angkaPertama * angkaKedua;
        double bagi = angkaPertama / angkaKedua;

        System.out.println("Hasil Tambah = " + tambah);
        System.out.println("Hasil Kurang = " + kurang);
        System.out.println("Hasil Kali = " + kali);
        System.out.println("Hasil Bagi = " + bagi);
    }
}

